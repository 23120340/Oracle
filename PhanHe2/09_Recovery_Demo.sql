CONNECT BVADMIN/"BVAdmin@2025";

ALTER TABLE HSBA_DV ENABLE ROW MOVEMENT;

-- Tạo CHECKPOINT_LOG nếu chưa có. Dùng ALL_TABLES theo CURRENT_SCHEMA (đúng cả khi chạy bằng
-- BVADMIN trực tiếp lẫn khi setup.ps1 chạy bằng SYS + ALTER SESSION SET CURRENT_SCHEMA=BVADMIN),
-- và bắt ORA-00955 phòng trường hợp bảng đã được file 07 tạo.
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
    FROM   ALL_TABLES
    WHERE  TABLE_NAME = 'CHECKPOINT_LOG'
      AND  OWNER = SYS_CONTEXT('USERENV','CURRENT_SCHEMA');

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE CHECKPOINT_LOG (
                EVENT_NAME VARCHAR2(100) PRIMARY KEY,
                SCN        NUMBER NOT NULL,
                CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP
            )
        ]';
    END IF;
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;  -- -955 = name already used → bỏ qua
END;
/

MERGE INTO CHECKPOINT_LOG c
USING (
    SELECT 'demo_before_delete_hsba_dv' AS event_name,
           DBMS_FLASHBACK.GET_SYSTEM_CHANGE_NUMBER AS scn
    FROM dual
) s
ON (c.EVENT_NAME = s.EVENT_NAME)
WHEN MATCHED THEN
    UPDATE SET c.SCN = s.SCN, c.CREATED_AT = SYSTIMESTAMP
WHEN NOT MATCHED THEN
    INSERT (EVENT_NAME, SCN) VALUES (s.EVENT_NAME, s.SCN);
COMMIT;

