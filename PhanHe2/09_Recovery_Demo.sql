PROMPT === Demo Flashback Query cho DONTHUOC ===
SELECT MAHSBA, NGAYDT, TENTHUOC, LIEUDUNG
FROM DONTHUOC AS OF TIMESTAMP (SYSTIMESTAMP - INTERVAL '5' MINUTE)
WHERE MAHSBA = 'HS001'
ORDER BY NGAYDT, TENTHUOC;

SELECT VERSIONS_STARTTIME, VERSIONS_OPERATION, MAHSBA, TENTHUOC, LIEUDUNG
FROM DONTHUOC VERSIONS BETWEEN TIMESTAMP MINVALUE AND MAXVALUE
WHERE MAHSBA = 'HS001'
ORDER BY VERSIONS_STARTTIME DESC NULLS LAST;
